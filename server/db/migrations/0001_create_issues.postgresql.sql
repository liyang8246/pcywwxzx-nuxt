CREATE TABLE IF NOT EXISTS issues (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uid TEXT NOT NULL,
  name TEXT NOT NULL,
  "class" TEXT NOT NULL,
  problem TEXT NOT NULL,
  phone TEXT NOT NULL,
  reg_time BIGINT NOT NULL,
  app_time BIGINT NOT NULL,
  closed BOOLEAN NOT NULL DEFAULT FALSE,
  closed_time BIGINT
);
